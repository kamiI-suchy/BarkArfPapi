-- 6) Imiona i nazwiska pracowników zarabiających co najmniej 4489.34 zł
SELECT Imie, Nazwisko
FROM Pracownicy
WHERE Zarobki >= 4489.34;

-- 7) Lista pracowników z nazwami przypisanych zespołów
SELECT p.Imie, p.Nazwisko, z.Nazwa_zespolu
FROM Pracownicy p
LEFT JOIN Zespoly z ON z.Nr_zespolu = p.Nr_zespolu;

-- 8) Lista działów wraz z nazwiskami ich szefów
SELECT d.Nazwa AS Dzial, p.Nazwisko AS Szef
FROM Dzialy d
JOIN Pracownicy p ON p.Nr_prac = d.Szef_dzialu;

-- 9) Nazwy działów bez przyporządkowanego zespołu
SELECT d.Nazwa
FROM Dzialy d
LEFT JOIN Zespoly z ON z.Nr_dzialu = d.Nr_dzialu
WHERE z.Nr_zespolu IS NULL;

-- 10) Nazwiska pracowników niebędących szefem żadnego działu
SELECT p.Nazwisko
FROM Pracownicy p
LEFT JOIN Dzialy d ON d.Szef_dzialu = p.Nr_prac
WHERE d.Nr_dzialu IS NULL;

-- 11) Nazwiska i zarobki kierowników zespołów zatrudnionych po roku {X1}
-- Przykład: X1 = 2001
SELECT p.Nazwisko, p.Zarobki
FROM Pracownicy p
JOIN Zespoly z ON z.Kierownik = p.Nr_prac
WHERE EXTRACT(YEAR FROM p.Data_zatrudnienia) > 2001;

-- 12) Nazwiska osób będących jednocześnie kierownikiem zespołu i szefem działu
SELECT DISTINCT p.Nazwisko
FROM Pracownicy p
JOIN Zespoly z ON z.Kierownik = p.Nr_prac
JOIN Dzialy d ON d.Szef_dzialu = p.Nr_prac;

-- 13) Imiona i nazwiska osób w zespołach o budżecie > {X2}
-- Przykład: X2 = 16000
SELECT p.Imie, p.Nazwisko
FROM Pracownicy p
JOIN Zespoly z ON z.Nr_zespolu = p.Nr_zespolu
WHERE z.Budzet > 16000;

-- 14) Osoby doświadczone dla zespołu (zatrudnione przed datą powołania zespołu)
SELECT p.Imie, p.Nazwisko, z.Nazwa_zespolu
FROM Pracownicy p
JOIN Zespoly z ON z.Nr_zespolu = p.Nr_zespolu
WHERE p.Data_zatrudnienia < z.Data_powolania;

-- 15) Osoby na stanowisku {X3} w zespołach z budżetem <= {X4}
-- Przykład: X3 = 'programista', X4 = 3000
SELECT p.Imie, p.Nazwisko
FROM Pracownicy p
JOIN Zespoly z ON z.Nr_zespolu = p.Nr_zespolu
WHERE LOWER(p.Stanowisko) = LOWER('programista')
  AND z.Budzet <= 3000;
