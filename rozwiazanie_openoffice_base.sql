CREATE TABLE Dzialy (
    Nr_dzialu INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nazwa VARCHAR(100) NOT NULL UNIQUE,
    Lokalizacja VARCHAR(100) NOT NULL,
    Szef_dzialu INTEGER
);

CREATE TABLE Zespoly (
    Nr_zespolu INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nazwa_zespolu VARCHAR(100) NOT NULL UNIQUE,
    Data_powolania DATE NOT NULL,
    Budzet DECIMAL(12,2) NOT NULL,
    Kierownik INTEGER,
    Nr_dzialu INTEGER,
    CONSTRAINT FK_Zespoly_Dzialy FOREIGN KEY (Nr_dzialu) REFERENCES Dzialy(Nr_dzialu)
);

CREATE TABLE Pracownicy (
    Nr_prac INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Imie VARCHAR(80) NOT NULL,
    Nazwisko VARCHAR(80) NOT NULL,
    Stanowisko VARCHAR(80) NOT NULL,
    Zarobki DECIMAL(10,2) NOT NULL,
    Data_zatrudnienia DATE NOT NULL,
    Nr_zespolu INTEGER,
    CONSTRAINT FK_Pracownicy_Zespoly FOREIGN KEY (Nr_zespolu) REFERENCES Zespoly(Nr_zespolu)
);

ALTER TABLE Dzialy
